CREATE TABLE CATEGORIE (
    ID_CATEGORIE VARCHAR(50) PRIMARY KEY,
    POIDS VARCHAR(50)
);

CREATE TABLE SALLE (
    NOM_SALLE VARCHAR(50) PRIMARY KEY,
    CAPACITE INT
);

CREATE TABLE COTISATIONS (
    ID_COTISATION VARCHAR(50) PRIMARY KEY,
    MONTANT_ANNUEL DECIMAL(10,2)
);

CREATE TABLE PAIEMENT (
    NUM_PAIEMENT VARCHAR(50) PRIMARY KEY,
    MONTANT_VERSER DECIMAL(10,2),
    DATE_VERSE DATE,
    MODE_VERSEMENT VARCHAR(50)
);

-- Table Adhérent avec relation récursive (parrainage)
CREATE TABLE ADHERENT (
    NUM_LICENCE_FFB VARCHAR(50) PRIMARY KEY,
    NOM VARCHAR(50) NOT NULL,
    PRENOM VARCHAR(50) NOT NULL,
    DATE_NAISSANCE DATE,
    SEXE CHAR(1),
    ADRESSE VARCHAR(100),
    TELEPHONE VARCHAR(15),
    CERTIFICAT VARCHAR(3),
    NUM_LICENCE_FFB_PARRAIN VARCHAR(50),
    NUM_PAIEMENT VARCHAR(50),
    ID_COTISATION VARCHAR(50),
    ID_CATEGORIE VARCHAR(50),
    FOREIGN KEY (NUM_LICENCE_FFB_PARRAIN) REFERENCES ADHERENT(NUM_LICENCE_FFB) ON DELETE SET NULL,
    FOREIGN KEY (NUM_PAIEMENT) REFERENCES PAIEMENT(NUM_PAIEMENT) ON DELETE CASCADE,
    FOREIGN KEY (ID_COTISATION) REFERENCES COTISATIONS(ID_COTISATION) ON DELETE CASCADE,
    FOREIGN KEY (ID_CATEGORIE) REFERENCES CATEGORIE(ID_CATEGORIE) ON DELETE CASCADE
);

CREATE TABLE SCEANCE (
    ID_SCEANCE VARCHAR(50) PRIMARY KEY,
    JOUR VARCHAR(50),
    HEURE TIME,
    NOM_SALLE VARCHAR(50),
    FOREIGN KEY (NOM_SALLE) REFERENCES SALLE(NOM_SALLE) ON DELETE CASCADE
);

-- Tables d'associations
CREATE TABLE ENCADRER (
    NUM_LICENCE_FFB VARCHAR(50),
    ID_SCEANCE VARCHAR(50),
    PRIMARY KEY (NUM_LICENCE_FFB, ID_SCEANCE),
    FOREIGN KEY (NUM_LICENCE_FFB) REFERENCES ADHERENT(NUM_LICENCE_FFB) ON DELETE CASCADE,
    FOREIGN KEY (ID_SCEANCE) REFERENCES SCEANCE(ID_SCEANCE) ON DELETE CASCADE
);

CREATE TABLE PARTICIPER (
    NUM_LICENCE_FFB VARCHAR(50),
    ID_SCEANCE VARCHAR(50),
    NOM_SALLE VARCHAR(50),
    PRIMARY KEY (NUM_LICENCE_FFB, ID_SCEANCE, NOM_SALLE),
    FOREIGN KEY (NUM_LICENCE_FFB) REFERENCES ADHERENT(NUM_LICENCE_FFB) ON DELETE CASCADE,
    FOREIGN KEY (ID_SCEANCE) REFERENCES SCEANCE(ID_SCEANCE) ON DELETE CASCADE,
    FOREIGN KEY (NOM_SALLE) REFERENCES SALLE(NOM_SALLE) ON DELETE CASCADE
);
