-- SELECTIONS (5)
-- 1. Adhérents parisiens
SELECT * FROM ADHERENT WHERE ADRESSE LIKE '%Paris%';
-- 2. Adhérents nés après 1995
SELECT * FROM ADHERENT WHERE DATE_NAISSANCE > '1995-01-01';
-- 3. Cotisations entre 100 et 300
SELECT * FROM COTISATIONS WHERE MONTANT_ANNUEL BETWEEN 100 AND 300;
-- 4. Modes de paiements uniques
SELECT DISTINCT MODE_VERSEMENT FROM PAIEMENT;
-- 5. Adhérents CAT1 ou CAT2 triés par nom
SELECT * FROM ADHERENT WHERE ID_CATEGORIE IN ('CAT1', 'CAT2') ORDER BY NOM;

-- AGREGATIONS (5)
-- 6. Nombre total de boxeurs
SELECT COUNT(*) FROM ADHERENT;
-- 7. Revenu total du club
SELECT SUM(MONTANT_VERSER) FROM PAIEMENT;
-- 8. Moyenne des paiements par mode
SELECT MODE_VERSEMENT, AVG(MONTANT_VERSER) FROM PAIEMENT GROUP BY MODE_VERSEMENT;
-- 9. Séances avec plus de 2 participants
SELECT ID_SCEANCE, COUNT(*) FROM PARTICIPER GROUP BY ID_SCEANCE HAVING COUNT(*) >= 1;
-- 10. Cotisation la plus chère
SELECT MAX(MONTANT_ANNUEL) FROM COTISATIONS;

-- JOINTURES (5)
-- 11. Boxeurs et leur poids (Interne)
SELECT a.NOM, c.POIDS FROM ADHERENT a JOIN CATEGORIE c ON a.ID_CATEGORIE = c.ID_CATEGORIE;
-- 12. Planning complet (Multiple)
SELECT a.NOM, s.JOUR, p.NOM_SALLE FROM PARTICIPER p JOIN ADHERENT a ON p.NUM_LICENCE_FFB = a.NUM_LICENCE_FFB JOIN SCEANCE s ON p.ID_SCEANCE = s.ID_SCEANCE;
-- 13. Tous les adhérents et leurs parrains (Externe/Récursive)
SELECT f.NOM AS Filleul, p.NOM AS Parrain FROM ADHERENT f LEFT JOIN ADHERENT p ON f.NUM_LICENCE_FFB_PARRAIN = p.NUM_LICENCE_FFB;
-- 14. Paiements par adhérent
SELECT a.NOM, p.MONTANT_VERSER FROM ADHERENT a JOIN PAIEMENT p ON a.NUM_PAIEMENT = p.NUM_PAIEMENT;
-- 15. Salles par séance
SELECT s.ID_SCEANCE, sa.NOM_SALLE FROM SCEANCE s JOIN SALLE sa ON s.NOM_SALLE = sa.NOM_SALLE;

-- IMBRIQUEES (5)
-- 16. Adhérents ayant payé (EXISTS)
SELECT NOM FROM ADHERENT a WHERE EXISTS (SELECT 1 FROM PAIEMENT p WHERE a.NUM_PAIEMENT = p.NUM_PAIEMENT);
-- 17. Boxeurs du Mercredi (IN)
SELECT NOM FROM ADHERENT WHERE NUM_LICENCE_FFB IN (SELECT NUM_LICENCE_FFB FROM PARTICIPER WHERE ID_SCEANCE IN (SELECT ID_SCEANCE FROM SCEANCE WHERE JOUR = 'Mercredi'));
-- 18. Paiements > tous les chèques (ALL)
SELECT * FROM PAIEMENT WHERE MONTANT_VERSER > ALL (SELECT MONTANT_VERSER FROM PAIEMENT WHERE MODE_VERSEMENT = 'Chèque');
-- 19. Catégories sans boxeurs (NOT IN)
SELECT ID_CATEGORIE FROM CATEGORIE WHERE ID_CATEGORIE NOT IN (SELECT ID_CATEGORIE FROM ADHERENT);
-- 20. Filleuls de parrains parisiens (IN)
SELECT NOM FROM ADHERENT WHERE NUM_LICENCE_FFB_PARRAIN IN (SELECT NUM_LICENCE_FFB FROM ADHERENT WHERE ADRESSE LIKE '%Paris%');
